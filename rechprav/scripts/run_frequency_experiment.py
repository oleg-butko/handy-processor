#!/usr/bin/env python3
"""Compare dictionary size and B2 frequency policy on the unchanged B1 fixture."""
import argparse
import csv
import hashlib
import json
import platform
import subprocess
import time
from pathlib import Path


def digest(path):
    with path.open("rb") as file:
        return hashlib.file_digest(file, "sha256").hexdigest()


def save(path, data):
    with path.open("x", encoding="utf-8") as file:
        json.dump(data, file, ensure_ascii=False, indent=2)
        file.write("\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output_dir", type=Path)
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    binary = root / "target/release/rechprav"
    profiler = root / "target/release/examples/profile"
    corpus = root / "data/fixtures/baseline/corpus.jsonl"
    data_hash = digest(corpus)
    resources = root / "artifacts/opencorpora-wordfreq"
    resource_manifest = json.loads((resources / "manifest.json").read_text())
    for file, expected in resource_manifest["output_sha256"].items():
        if digest(resources / file) != expected:
            raise ValueError(f"resource hash mismatch: {file}")
    if digest(root / "scripts/prepare_resources.py") != resource_manifest["script_sha256"]:
        raise ValueError("resources were generated by a different exporter")
    validated = json.loads(subprocess.check_output([str(binary), "validate", str(corpus)]))
    if validated["real_asr"] or validated["pending"] or validated["ambiguous"]:
        raise ValueError("experiment requires reviewed synthetic examples only")
    output = args.output_dir.resolve()
    output.mkdir()
    save(output / "validation.json", validated)
    save(output / "resource-manifest.json", resource_manifest)
    profiles = {
        "keep": None,
        "b1-tiny": "baseline.toml",
        "b2-tiny": "frequency-tiny.toml",
        "b1-full": "opencorpora-b1.toml",
        "b2-full": "opencorpora-b2.toml",
        "b2-full-zero-frequency": "opencorpora-b2-zero-frequency.toml",
    }
    rows, commands, timings, errors = [], [], {}, []
    for name, config in profiles.items():
        command = [str(binary), "benchmark", str(corpus), "--output-dir", str(output / name)]
        if config:
            command += ["--config", str(root / "configs" / config)]
        commands.append(command)
        start = time.perf_counter()
        process = subprocess.run(command, capture_output=True, text=True)
        timings[name] = time.perf_counter() - start
        if process.returncode:
            save(output / "failure.json", {"command":command,"stderr":process.stderr})
            process.check_returncode()
        manifest = json.loads((output / name / "manifest.json").read_text())
        if manifest["input_sha256"] != data_hash:
            raise ValueError("corpus changed during experiment")
        for file, expected in manifest["compiled_source_sha256"].items():
            if digest(root / file) != expected:
                raise ValueError(f"stale binary: {file}; rebuild")
        if config:
            expected_dictionary = resource_manifest["output_sha256"]["dictionary.txt"] if "full" in name else digest(root / "data/fixtures/baseline/dictionary.txt")
            if manifest["resources"]["resource_sha256"]["dictionary"] != expected_dictionary:
                raise ValueError("dictionary changed during experiment")
            if name.startswith("b2") and manifest["resources"]["resource_sha256"]["frequency"] != resource_manifest["output_sha256"]["frequency.tsv"]:
                raise ValueError("frequencies changed during experiment")
        metric = json.loads((output / name / "metrics.json").read_text())
        count = metric["counts_1_to_1"]
        rows.append({"profile":name,"tp":count["tp"],"fp":count["fp"],"fn":count["fn_"],
                     "harmed":count["harmed_correct_input"],"correct_positions":count["correct_input"],
                     "precision":metric["overall_precision"],"recall":metric["rates_1_to_1"]["recall"],
                     "fcr":metric["rates_1_to_1"]["false_correction_rate"],"wer_after":metric["wer_after"],
                     "candidate_recall_1":metric["candidate_recall_at_k"]["1"],
                     "candidate_recall_20":metric["candidate_recall_at_k"]["20"],
                     "incomplete_searches":metric["incomplete_searches"]})
        for line in (output / name / "predictions.jsonl").read_text().splitlines():
            prediction = json.loads(line)
            if prediction["prediction"] != prediction["gold"]:
                errors.append({"profile":name,**prediction})
        print(json.dumps(rows[-1]), flush=True)
        if name in ["b1-tiny", "b1-full", "b2-full"]:
            command = [str(profiler), str(root / "configs" / config), str(corpus)]
            commands.append(command)
            measured = json.loads(subprocess.check_output(command))
            for file, expected in measured["compiled_source_sha256"].items():
                if digest(root / file) != expected:
                    raise ValueError(f"stale profiler: {file}; rebuild examples")
            if measured["resources"] != manifest["resources"]:
                raise ValueError("profiler/benchmark resource mismatch")
            save(output / f"{name}-performance.json", measured)
    with (output / "comparison.csv").open("x", encoding="utf-8", newline="") as file:
        writer = csv.DictWriter(file, fieldnames=list(rows[0]), lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    with (output / "errors.jsonl").open("x", encoding="utf-8") as file:
        for row in errors:
            file.write(json.dumps(row, ensure_ascii=False) + "\n")
    save(output / "commands.json", commands)
    git_revision = subprocess.check_output(["git", "-C", str(root), "rev-parse", "HEAD"], text=True).strip()
    git_status = subprocess.check_output(["git", "-C", str(root), "status", "--porcelain", "--",
                                          "src", "tests", "scripts", "examples", "configs", "Cargo.toml", "Cargo.lock", "data/fixtures"], text=True)
    cpu = next((line.split(":", 1)[1].strip() for line in Path("/proc/cpuinfo").read_text().splitlines()
                if line.startswith("model name")), None)
    save(output / "environment.json", {"git_revision":git_revision,"implementation_status":git_status.splitlines(),
         "cpu":cpu,
         "platform":platform.platform(),"python":platform.python_version(),"dataset_sha256":data_hash,
         "binary_sha256":digest(binary),"profiler_sha256":digest(profiler),
         "profiler_source_sha256":digest(root / "examples/profile.rs"),
         "runner_sha256":digest(Path(__file__)),"whole_process_seconds":timings,
         "scope":"synthetic dev mechanism experiment; fixed heuristic parameters, no tuning or held-out quality estimate"})


if __name__ == "__main__":
    main()
